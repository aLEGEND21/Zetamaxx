"""Builds shared/fixtures/problems.json, the contract between the Python and
TypeScript generators. Both test suites must reproduce this file exactly.

Regenerate (only when the generator is changed on purpose):
    cd api && uv run python -m app.game.fixture
"""

import json
from pathlib import Path

from app.game.generator import generate_sequence
from app.game.prng import mulberry32
from app.game.settings import STANDARD

FIXTURE_PATH = Path(__file__).resolve().parents[3] / "shared" / "fixtures" / "problems.json"

SEEDS = [0, 1, 42, 123456789, 4294967295]
COUNT = 200
CONFIGS = {
    "standard": STANDARD,
    "custom": {
        "duration": 60,
        "ops": {"add": True, "sub": False, "mul": True, "div": True},
        "add": {"a": [10, 999], "b": [1, 50]},
        "mul": {"a": [3, 25], "b": [11, 19]},
    },
}


def build() -> dict:
    prng = {}
    for seed in SEEDS:
        rng = mulberry32(seed)
        prng[str(seed)] = [rng() for _ in range(10)]
    problems = {
        name: {
            str(seed): [
                [p["op"], p["a"], p["b"], p["answer"], p["display"]] for p in generate_sequence(seed, config, COUNT)
            ]
            for seed in SEEDS
        }
        for name, config in CONFIGS.items()
    }
    return {
        "note": "Generated by api/app/game/fixture.py. Rows are [op, a, b, answer, display].",
        "seeds": SEEDS,
        "count": COUNT,
        "configs": CONFIGS,
        "prng": prng,
        "problems": problems,
    }


if __name__ == "__main__":
    FIXTURE_PATH.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE_PATH.write_text(json.dumps(build(), ensure_ascii=False, separators=(",", ":")) + "\n")
    print(f"wrote {FIXTURE_PATH}")
